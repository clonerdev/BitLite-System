function buildSeries(baseHash: number, feePct: number, seedOffset: number): SharePoint[] {
  const points: SharePoint[] = [];
  const hours = [
    '15:00', '16:30', '18:00', '19:30', '21:00', '22:30', '00:00', '01:30',
    '03:00', '04:30', '06:00', '07:30', '09:00', '10:30', '12:00', '13:30',
    '15:00', '16:30', '18:00', '19:30', '21:00', '22:30', '00:00', '01:30'
  ];

  for (let i = 0; i < hours.length; i++) {
    const wave = Math.sin((i + seedOffset) * 0.65) * (baseHash * 0.06) + Math.cos(i * 1.2) * (baseHash * 0.03);
    const validHashrate = Math.max(0, Number((baseHash + wave).toFixed(2)));
    const feeHashrate = Number(((validHashrate * feePct) / 100).toFixed(2));
    const invalidHashrate = Number((validHashrate * (i % 7 === 0 ? 0.008 : 0.002)).toFixed(2));
    const validShares = Math.round(validHashrate * 4.2 + (i % 5) * 18);
    const feeShares = Math.max(1, Math.round((validShares * feePct) / 100));
    const invalidShares = i % 6 === 0 ? 3 : i % 4 === 0 ? 1 : 0;

    points.push({
      time: hours[i],
      validHashrate,
      invalidHashrate,
      feeHashrate,
      validShares,
      invalidShares,
      feeShares,
    });
  }
  return points;
}

